// Regenerates shared/caseNotes.js from the cases in index.html.
// The Archivist and practice quiz read ONLY these server-held notes, never text sent by the browser.
//   node tools/build-case-notes.mjs          write the file
//   node tools/build-case-notes.mjs --check  exit 1 if the file is out of date
import fs from 'fs';
import { loadCases } from './lib.mjs';
const OUT = new URL('../shared/caseNotes.js', import.meta.url);
const MAX = 3600;
export function buildNotesSource(cases = loadCases()){
  const notes = {};
  for (const c of cases){
    const decisions = c.type === 'full' ? [...c.leads.map(l => l.decision), c.convergeDecision, c.finalDecision] : [c.decision];
    const takeaways = decisions.map(d => (d.options.find(o => o.tier === 'ideal') || {}).resolution).filter(Boolean);
    const parts = [
      'Scenario: ' + c.blurb,
      'Background: ' + c.legacyBriefing.text,
      'Legacies: ' + c.legacyBriefing.legacies.map(l => l.name + ' (' + l.modernConnection + ')').join(' '),
      'Key terms: ' + (c.glossary || []).map(g => g.term + ': ' + g.def).join(' '),
      'What careful reasoning shows: ' + takeaways.join(' ')
    ];
    let text = parts.join('\n');
    if (text.length > MAX) text = text.slice(0, MAX - 1) + '…';
    notes[c.id] = { title: c.title, civ: c.civ, skill: c.skill, text };
  }
  return '// AUTO-GENERATED by tools/build-case-notes.mjs from the cases in index.html. Do not edit by hand.\n' +
         '// Re-run `node tools/build-case-notes.mjs` after changing any case text.\n' +
         'export const CASE_NOTES = ' + JSON.stringify(notes, null, 1) + ';\n';
}
if (process.argv[1] && process.argv[1].endsWith('build-case-notes.mjs')){
  const src = buildNotesSource();
  if (process.argv.includes('--check')){
    const cur = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (cur !== src){ console.error('shared/caseNotes.js is out of date. Run: node tools/build-case-notes.mjs'); process.exit(1); }
    console.log('caseNotes.js is up to date');
  } else { fs.writeFileSync(OUT, src); console.log('wrote shared/caseNotes.js (' + src.length + ' bytes)'); }
}
